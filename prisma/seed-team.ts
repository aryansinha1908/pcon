async function main() {
  console.log("Seeding team members...");
  for (const member of initialTeamMembers) {
    await prisma.teamMember.upsert({
      where: { id: member.id },
      update: {
        name: member.name,
        photo: member.photo,
        batch: member.batch,
        designation: member.designation,
        domain: member.domain,
        github: member.github,
        linkedin: member.linkedin,
        portfolio: member.portfolio,
        displayOrder: member.displayOrder,
        isActive: member.isActive,
      },
      create: {
        id: member.id,
        name: member.name,
        photo: member.photo,
        batch: member.batch,
        designation: member.designation,
        domain: member.domain,
        github: member.github,
        linkedin: member.linkedin,
        portfolio: member.portfolio,
        displayOrder: member.displayOrder,
        isActive: member.isActive,
      },
    });
    console.log(`Seeded team member: ${member.name} (${member.domain}, Batch ${member.batch})`);
  }
  console.log(`Finished seeding ${initialTeamMembers.length} team members.`);
}

main()
  .catch((e) => {
    console.error("Error seeding team members:", e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

